/**
 * Esta funcion calcula el area de una figura geometrica
 * @param {number} base es una dimensión
 * @param {number} altura es otra dimensión correlacionada con base
 * @return {number} devuelve el resultado de la multiplicacion de base y altura y lo divide entre 2 obteniendo el area
*/


function calcularArea(base, altura) {
return (base * altura) / 2;
}